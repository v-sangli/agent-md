#!/usr/bin/env bash
# Validate the agent-docs store and generate its INDEX.md.
# This script is the store's only validator: the functions after validate_all trust it.
set -euo pipefail
export LC_ALL=C

usage() {
  printf 'usage: agent_docs.sh [--root DIR] index|check\n' >&2
  exit 2
}

fail_store() { # WHERE REASON
  printf 'agent-docs: %s: %s\n' "$1" "$2" >&2
  exit 1
}

list_docs() { # ROOT -> sorted rel paths, one per line
  (cd "$1" && find . -path '*/.*' -prune -o -type f -name '*.md' ! -path ./INDEX.md -print) |
    sed 's|^\./||' | sort
}

description_of() { # ROOT REL -> the description text
  sed -n '2s/^description:[[:space:]]*//p' "$1/$2"
}

validate_doc() { # ROOT REL
  local file="$1/$2" line1 line2 line3
  line1="$(sed -n 1p "$file")"
  line2="$(sed -n 2p "$file")"
  line3="$(sed -n 3p "$file")"
  [ "$line1" = "---" ] || fail_store "$2" "no frontmatter"
  case "$line2" in
    description:*) ;;
    *) fail_store "$2" "unknown or extra frontmatter key" ;;
  esac
  [ -n "$(description_of "$1" "$2")" ] || fail_store "$2" "empty description"
  if [ "$line3" != "---" ]; then
    if [[ "$line3" =~ ^[A-Za-z_][A-Za-z0-9_-]*: ]]; then
      fail_store "$2" "unknown or extra frontmatter key"
    fi
    fail_store "$2" "description not on one line"
  fi
}

validate_all() { # ROOT -> the number of docs on stdout
  local rel n=0
  [ -d "$1" ] || fail_store "$1" "missing root"
  while IFS= read -r rel; do
    validate_doc "$1" "$rel"
    n=$((n + 1))
  done < <(list_docs "$1")
  printf '%d\n' "$n"
}

index_line() { # ROOT REL
  printf -- '- `%s`: %s\n' "$2" "$(description_of "$1" "$2")"
}

render_index() { # ROOT -> INDEX.md content on stdout
  local docs roots rel dir
  docs="$(list_docs "$1")"
  cat <<'EOF'
# Agent docs

Generated by `agent_docs.sh index` from each doc's frontmatter. Do not edit.
Paths are relative to the store root.
EOF
  roots="$(printf '%s\n' "$docs" | awk 'NF && !/\//')"
  if [ -n "$roots" ]; then
    printf '\n'
    while IFS= read -r rel; do
      index_line "$1" "$rel"
    done <<<"$roots"
  fi
  while IFS= read -r dir; do
    printf '\n## %s\n' "$dir"
    while IFS= read -r rel; do
      index_line "$1" "$rel"
    done < <(printf '%s\n' "$docs" | awk -v d="$dir" '{ p = $0; if (sub(/\/[^\/]*$/, "", p) && p == d) print }')
  done < <(printf '%s\n' "$docs" | awk '/\// { sub(/\/[^\/]*$/, ""); print }' | sort -u)
}

cmd_index() { # ROOT
  local n
  n="$(validate_all "$1")"
  render_index "$1" >"$1/INDEX.md"
  printf 'agent-docs: OK (%d docs)\n' "$n"
}

cmd_check() { # ROOT
  local n
  n="$(validate_all "$1")"
  [ -f "$1/INDEX.md" ] || fail_store "INDEX.md" "index missing"
  cmp -s <(render_index "$1") "$1/INDEX.md" || fail_store "INDEX.md" "index stale"
  printf 'agent-docs: OK (%d docs)\n' "$n"
}

root="$HOME/.agent-docs"
if [ "$#" -ge 2 ] && [ "$1" = "--root" ]; then
  root="$2"
  shift 2
fi
[ "$#" -eq 1 ] || usage
case "$1" in
  index) cmd_index "$root" ;;
  check) cmd_check "$root" ;;
  *) usage ;;
esac
